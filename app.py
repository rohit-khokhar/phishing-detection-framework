from flask import Flask, render_template, request, session, send_file
from predictor import predict_url, predict_email

from reportlab.platypus import SimpleDocTemplate, Paragraph
from reportlab.lib.styles import getSampleStyleSheet

from datetime import datetime
import io

app = Flask(__name__)
app.secret_key = "your_secret_key_here"


@app.route("/")
def home():
    return render_template("index.html")


@app.route("/predict_url", methods=["POST"])
def predict_url_route():
    url = request.form.get("url", "").strip()

    if not url:
        return render_template(
            "index.html",
            url_result={
                "prediction": "Error",
                "confidence": 0,
                "message": "Please enter a URL."
            }
        )

    try:
        result = predict_url(url)

        # Save report data
        session["input_type"] = "URL"
        session["input_text"] = url
        session["prediction"] = result.get("prediction", "")
        session["confidence"] = result.get("confidence", 0)
        session["message"] = result.get("message", "")

    except Exception as e:
        result = {
            "prediction": "Error",
            "confidence": 0,
            "message": str(e)
        }

    return render_template(
        "index.html",
        url_result=result
    )


