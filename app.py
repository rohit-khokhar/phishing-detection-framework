@app.route("/download_report")
def download_report():

    if "prediction" not in session:
        return "No prediction available. Please make a prediction first."

    buffer = io.BytesIO()

    doc = SimpleDocTemplate(buffer)

    styles = getSampleStyleSheet()

    story = []

    story.append(Paragraph("<b>PHISHING DETECTION REPORT</b>", styles["Title"]))
    story.append(Paragraph("<br/>", styles["Normal"]))

    story.append(
        Paragraph(
            f"<b>Date:</b> {datetime.now().strftime('%d-%m-%Y %H:%M:%S')}",
            styles["Normal"]
        )
    )

    story.append(Paragraph("<br/>", styles["Normal"]))

    story.append(
        Paragraph(
            f"<b>Input Type:</b> {session.get('input_type')}",
            styles["Normal"]
        )
    )

    story.append(
        Paragraph(
            f"<b>Input:</b> {session.get('input_text')}",
            styles["Normal"]
        )
    )

    story.append(
        Paragraph(
            f"<b>Prediction:</b> {session.get('prediction')}",
            styles["Normal"]
        )
    )

    story.append(
        Paragraph(
            f"<b>Confidence:</b> {session.get('confidence')}%",
            styles["Normal"]
        )
    )

    story.append(
        Paragraph(
            f"<b>Message:</b> {session.get('message')}",
            styles["Normal"]
        )
    )

    story.append(Paragraph("<br/>", styles["Normal"]))

    story.append(
        Paragraph(
            "<b>Generated by:</b><br/>"
            "Intelligent Multi-Layered Phishing Detection Framework",
            styles["Normal"]
        )
    )

    doc.build(story)

    buffer.seek(0)

    return send_file(
        buffer,
        as_attachment=True,
        download_name="Phishing_Report.pdf",
        mimetype="application/pdf"
    )


if __name__ == "__main__":
    app.run(debug=True)